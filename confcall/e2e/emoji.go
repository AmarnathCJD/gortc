// emojisFromMAC reduces an HMAC output to four emojis from emojiSet.
// Splits the first 32 bytes of the MAC into four 64-bit chunks, mods
// each by len(emojiSet).
func emojisFromMAC(mac []byte) []string {
	out := make([]string, 4)
	for i := 0; i < 4; i++ {
		chunk := binary.BigEndian.Uint64(mac[i*8 : (i+1)*8])
		out[i] = emojiSet[int(chunk%uint64(len(emojiSet)))]
	}
	return out
}
